#! /usr/bin/env bash
# generates make/toolchain/target/uclibc/patches/separate/702-reproducible-data.patch
MYPWD="$(dirname $(realpath $0))"
NGPWD="$(realpath $MYPWD/../../../../)"
echo -n "generating: "

[ "$(LC_ALL="C.UTF-8"     locale charmap 2>/dev/null)" != "UTF-8"      ] && echo "Locale required: C.UTF-8"             >&2 && exit 1
[ "$(LC_ALL="en_US.UTF-8" locale charmap 2>/dev/null)" != "UTF-8"      ] && echo "Locale required: en_US.UTF-8"         >&2 && exit 1
[ "$(LC_ALL="en_US"       locale charmap 2>/dev/null)" != "ISO-8859-1" ] && echo "Locale required: en_US (ISO-8859-1)"  >&2 && exit 1

LIBCVER="$(getconf GNU_LIBC_VERSION 2>/dev/null || echo unknown)"

UCNGVER="${1:-$(sed -n 's/^UCLIBC_HASH_//p' $MYPWD/uclibc.mk | tail -n1 | sed 's/ *=.*//')}"
UCNGTAR="$NGPWD/dl/uClibc-ng-${UCNGVER}.tar.xz"
[ ! -s "$UCNGTAR" ] && echo "Source not found: $UCNGTAR" && exit 1

WORKPWD="$NGPWD/uclibc-wctables"
trap 'rm -rf "$WORKPWD"' EXIT
rm -rf "$WORKPWD"
mkdir -p "$WORKPWD"
[ ! -d "$WORKPWD" ] && echo "Failed creating directory: $WORKPWD" && exit 1

echo -n "unpacking ... "
tar xf "$UCNGTAR" -C "$WORKPWD" --strip-components=1
mkdir -p "$WORKPWD/host/include/bits"
[ ! -f "$WORKPWD/Makefile" ] && echo "Failed unpacking to: $WORKPWD" && exit 1

echo -n "wctables.h ... "
cp "$WORKPWD/libc/sysdeps/linux/common/bits/uClibc_charclass.h" "$WORKPWD/host/include/bits/"
gcc -std=gnu99 -O2 -I"$WORKPWD/host" "$WORKPWD/extra/locale/gen_wctype.c" -o "$WORKPWD/host/gen_wctype"
"$WORKPWD/host/gen_wctype" "C.UTF-8" > "$WORKPWD/wctables.h.freetz"
! grep -q '^#define __LOCALE_DATA_WCuplow_diffs' "$WORKPWD/wctables.h.freetz" && echo "Error creating file: wctables.h.freetz" && exit 1

echo -n "c8tables.h ... "
cp "$WORKPWD/libc/sysdeps/linux/common/bits/uClibc_ctype.h" "$WORKPWD/host/include/bits/"
gcc -std=gnu99 -O2 -D__UCLIBC_GEN_LOCALE -DCTYPE_PACKED=1 -DDO_WIDE_CHAR=1 -I"$WORKPWD/host" "$WORKPWD/extra/locale/gen_wc8bit.c" -o "$WORKPWD/host/gen_wc8bit" 2>/dev/null
"$WORKPWD/host/gen_wc8bit" "$WORKPWD/extra/locale/charmaps/ASCII.pairs" "$WORKPWD/extra/locale/charmaps/ISO-8859-1.pairs" > "$WORKPWD/host/c8tables.h" 2>/dev/null
! grep -Eq '^#define __LOCALE_DATA_NUM_CODESETS[[:space:]]+2$' "$WORKPWD/host/c8tables.h" && echo "Error creating file: c8tables.h.freetz" && exit 1

echo -n "locale_tables.h ... "
cat > "$WORKPWD/host/locales.txt" <<'EOF'
@euro e
#-
UTF-8 yes
8-BIT yes
#-
en_US.UTF-8 UTF-8
en_US ISO-8859-1
EOF
gcc -std=gnu99 -O2 -D_GNU_SOURCE -I"$WORKPWD/host" "$WORKPWD/extra/locale/gen_locale.c" -o "$WORKPWD/host/gen_locale"
"$WORKPWD/host/gen_locale" -o "$WORKPWD/host/locale_tables.h" "$WORKPWD/host/locales.txt"
! grep -Eq '^#define __LOCALE_DATA_NUM_LOCALES[[:space:]]+3$' "$WORKPWD/host/locale_tables.h" && echo "Error creating file: locale_tables.h.freetz" && exit 1

echo -n "patching ... "
(
	echo
	echo "  Do not edit this file! Run generate.sh to create it."
	echo "  Generated with uClibc-ng $UCNGVER ($LIBCVER)"
	echo
	diff -u --label "/dev/null" --label "extra/locale/wctables.h.freetz"      "/dev/null" "$WORKPWD/wctables.h.freetz"
	diff -u --label "/dev/null" --label "extra/locale/c8tables.h.freetz"      "/dev/null" "$WORKPWD/host/c8tables.h"
	diff -u --label "/dev/null" --label "extra/locale/locale_tables.h.freetz" "/dev/null" "$WORKPWD/host/locale_tables.h"
) > "$MYPWD/patches/separate/702-reproducible-data.patch"

echo "done."

